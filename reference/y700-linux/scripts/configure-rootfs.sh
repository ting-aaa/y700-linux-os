#!/bin/bash
set -Eeuo pipefail
PROJECT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
ROOTFS=$(realpath -- "${1:?rootfs directory required}")
[[ "$ROOTFS" == /home/builder/y700-linux-build*/debian-rootfs ]] || {
  echo 'Rootfs must be inside the dedicated Y700 build tree.' >&2; exit 1;
}
test -f "$ROOTFS/etc/debian_version"
install -d "$ROOTFS/etc/y700" "$ROOTFS/usr/local/sbin" "$ROOTFS/etc/systemd/system"
printf 'y700-linux\n' > "$ROOTFS/etc/hostname"
printf '127.0.0.1 localhost\n127.0.1.1 y700-linux\n::1 localhost ip6-localhost ip6-loopback\n' > "$ROOTFS/etc/hosts"
printf 'en_US.UTF-8 UTF-8\nzh_CN.UTF-8 UTF-8\n' > "$ROOTFS/etc/locale.gen"
chroot "$ROOTFS" locale-gen
printf 'LANG=en_US.UTF-8\n' > "$ROOTFS/etc/default/locale"
ln -sfn /usr/share/zoneinfo/Asia/Shanghai "$ROOTFS/etc/localtime"
ln -sfn /run/NetworkManager/resolv.conf "$ROOTFS/etc/resolv.conf"
printf 'Asia/Shanghai\n' > "$ROOTFS/etc/timezone"
chroot "$ROOTFS" id y700 >/dev/null 2>&1 || chroot "$ROOTFS" useradd -m -s /bin/bash -G sudo,audio,video,input,render,netdev,bluetooth y700
chroot "$ROOTFS" passwd -l root
chroot "$ROOTFS" passwd -l y700
printf '# Root is selected by initramfs UUID; no Android partitions are mounted.\n' > "$ROOTFS/etc/fstab"
printf 'Y700 Linux experimental PC build. Hardware has not been validated.\n' > "$ROOTFS/etc/motd"
install -m 0755 "$PROJECT/rootfs-overlay/y700-firstboot" "$ROOTFS/usr/local/sbin/y700-firstboot"
install -m 0755 "$PROJECT/rootfs-overlay/y700-hardware-report" "$ROOTFS/usr/local/sbin/y700-hardware-report"
install -m 0644 "$PROJECT/rootfs-overlay/y700-firstboot.service" "$ROOTFS/etc/systemd/system/y700-firstboot.service"
systemctl --root="$ROOTFS" enable NetworkManager.service bluetooth.service lightdm.service y700-firstboot.service
systemctl --root="$ROOTFS" set-default graphical.target
# Keep container service idle until the user explicitly starts it after kernel acceptance.
systemctl --root="$ROOTFS" disable docker.service docker.socket containerd.service || true
# Machine identity and host keys must be generated by the actual installed system.
: > "$ROOTFS/etc/machine-id"
if [[ -f "$ROOTFS/var/lib/dbus/machine-id" && ! -L "$ROOTFS/var/lib/dbus/machine-id" ]]; then
  rm -- "$ROOTFS/var/lib/dbus/machine-id"
fi
ln -sfn /etc/machine-id "$ROOTFS/var/lib/dbus/machine-id"
